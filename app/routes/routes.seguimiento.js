import { Router } from 'express';
import express from 'express';
import verificarToken from '../middleware/auth.middleware.js';
import verificarRol from '../middleware/rol.middleware.js';
import { getDashboard, getPlaneaciones, getPlanesAccion, crearPlaneacion, getSeguimiento, crearCalificacion, revisarCalificacion, subirEvidencia, descargarEvidencia, getEvidencias, getAuditoria, getNotificaciones, marcarNotificacionLeida } from '../controllers/controller.seguimiento.js';
const router = Router();
router.get('/dashboard', verificarToken, getDashboard);
router.get('/seguimiento/planeacion', verificarToken, getPlaneaciones);
router.get('/seguimiento/planes_accion', verificarToken, getPlanesAccion);
router.post('/seguimiento/planeacion', verificarToken, verificarRol(1,2,3), crearPlaneacion);
router.get('/seguimiento/calificaciones', verificarToken, getSeguimiento);
router.post('/seguimiento/calificaciones', verificarToken, crearCalificacion);
router.put('/seguimiento/calificaciones/:id/revision', verificarToken, verificarRol(1,2), revisarCalificacion);
router.post('/seguimiento/evidencias', verificarToken, express.raw({ type: 'application/octet-stream', limit: '10mb' }), subirEvidencia);
router.get('/seguimiento/calificaciones/:calificacionId/evidencias', verificarToken, getEvidencias);
router.get('/seguimiento/evidencias/:id/descargar', verificarToken, descargarEvidencia);
router.get('/auditoria', verificarToken, verificarRol(1,2), getAuditoria);
router.get('/notificaciones', verificarToken, getNotificaciones);
router.put('/notificaciones/:id/leida', verificarToken, marcarNotificacionLeida);
export default router;
